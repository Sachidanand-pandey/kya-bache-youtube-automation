
"""Upload one validated daily children's story video."""

import json
import os
from pathlib import Path

from google.oauth2.credentials import Credentials
from google.auth.transport.requests import Request
from googleapiclient.discovery import build
from googleapiclient.http import MediaFileUpload

BASE = Path(__file__).resolve().parent.parent
OUTPUT = BASE / "output"

SCOPES = ["https://www.googleapis.com/auth/youtube.upload"]


def create_youtube():

    credentials = Credentials(
        token=None,
        refresh_token=os.environ["YOUTUBE_REFRESH_TOKEN"],
        token_uri="https://oauth2.googleapis.com/token",
        client_id=os.environ["YOUTUBE_CLIENT_ID"],
        client_secret=os.environ["YOUTUBE_CLIENT_SECRET"],
        scopes=SCOPES,
    )

    credentials.refresh(Request())

    return build("youtube", "v3", credentials=credentials)


def upload_one_video(youtube, path, metadata):

    if not path.exists() or path.stat().st_size == 0:
        raise FileNotFoundError(
            f"Video missing or empty: {path}"
        )

    body = {
        "snippet": {
            "title": metadata["title"][:100],
            "description": metadata["description"],
            "tags": metadata.get("tags", []),
            "categoryId": metadata.get("category_id", "22"),
            "defaultLanguage": "hi",
        },
        "status": {
            "privacyStatus": os.getenv(
                "YOUTUBE_PRIVACY", "public"
            ),
            "selfDeclaredMadeForKids": True,
        },
    }

    media = MediaFileUpload(
        str(path),
        mimetype="video/mp4",
        chunksize=5 * 1024 * 1024,
        resumable=True
    )

    request = youtube.videos().insert(
        part="snippet,status",
        body=body,
        media_body=media
    )

    response = None

    while response is None:

        status, response = request.next_chunk()

        if status:
            print(
                f"{path.name}: "
                f"{int(status.progress() * 100)}%",
                flush=True
            )

    url = "https://www.youtube.com/watch?v=" + response["id"]

    print("Uploaded:", url, flush=True)

    return url


def main():

    story_path = OUTPUT / "story.json"
    metadata_path = OUTPUT / "upload_metadata.json"
    video_path = OUTPUT / "daily_video.mp4"

    if not story_path.exists() or not metadata_path.exists():
        raise RuntimeError(
            "Story or upload metadata is missing."
        )

    story = json.loads(
        story_path.read_text(encoding="utf-8")
    )

    metadata = json.loads(
        metadata_path.read_text(encoding="utf-8")
    )

    # Validate Groq story
    if story.get("source") != "groq":
        raise RuntimeError(
            "Story was not generated by Groq. Refusing upload."
        )

    if metadata.get("story_source") != "groq":
        raise RuntimeError(
            "Upload metadata source is not Groq. Refusing upload."
        )

    if len(story.get("scenes", [])) != 12:
        raise RuntimeError(
            "Story must contain exactly 12 scenes."
        )

    if metadata.get("scene_count") != 12:
        raise RuntimeError(
            "Metadata scene count must be 12."
        )

    if not metadata.get("title") or not metadata.get("description"):
        raise RuntimeError(
            "Upload metadata is incomplete."
        )

    youtube = create_youtube()

    upload_one_video(
        youtube,
        video_path,
        metadata
    )


if __name__ == "__main__":
    main()
